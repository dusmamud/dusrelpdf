import 'dart:io';
import 'dart:typed_data';

import 'package:dusrelpdf_flutter/dusrelpdf_flutter.dart';
import 'package:test/test.dart';

// Tests for the Flutter plugin package. These are pure dart tests
// (package:test, no flutter_test) so they run with `dart test` — but
// the native-library tests need the Rust cdylib built first:
//
//   cargo build -p dusrelpdf-ffi --release
//
// Run from this package directory:
//   dart test test/dusrelpdf_flutter_test.dart
//
// Do NOT run plain `dart test` on the whole test/ directory: the
// widget test (dusrelpdf_flutter_widget_test.dart) imports
// package:flutter_test and only runs under `flutter test`.
//
// Fixtures are copies of the pure-Dart package's fixtures (real PDFs
// generated by the repo's own CLI):
//   cargo run -p dusrelpdf-cli -- mock --pages 3 -o test/testdata/three.pdf
//   cargo run -p dusrelpdf-cli -- mock --pages 5 -o test/testdata/five.pdf

Uint8List fixture(String name) => File('test/testdata/$name').readAsBytesSync();

void main() {
  group('DusrelpdfFlutter', () {
    test('defaultLibraryPath is platform-correct (no native lib needed)',
        () {
      final path = DusrelpdfFlutter.defaultLibraryPath();
      if (Platform.isWindows) {
        expect(path, 'dusrelpdf.dll');
      } else if (Platform.isIOS || Platform.isMacOS) {
        expect(path, endsWith('Frameworks/Dusrelpdf.framework/Dusrelpdf'));
      } else {
        // Android + Linux.
        expect(path, 'libdusrelpdf.so');
      }
    });

    test('re-exports the dusrelpdf API', () {
      // These types must be visible through the plugin import alone.
      expect(Dusrelpdf, isNotNull);
      expect(DusrelException, isNotNull);
      expect(PdfInfo, isNotNull);
      expect(DusrelpdfFlutter, isNotNull);
    });
  });

  // Everything below goes through the real cdylib + Rust core.
  group('native operations (needs cargo-built libdusrelpdf)', () {
    late DusrelpdfFlutter pdf;

    setUpAll(() {
      pdf = DusrelpdfFlutter();
    });

    test('is a Dusrelpdf', () {
      expect(pdf, isA<Dusrelpdf>());
    });

    test('version', () {
      expect(pdf.version, '0.1.0');
    });

    test('merge 3-page + 5-page fixtures = 8 pages', () {
      final merged = pdf.merge([fixture('three.pdf'), fixture('five.pdf')]);
      expect(pdf.getPdfInfo(merged).pageCount, 8);
    });

    test('invalid range throws DusrelException with INVALID_RANGE', () {
      expect(
        () => pdf.extractPagesRange(fixture('three.pdf'), '9'),
        throwsA(isA<DusrelException>()
            .having((e) => e.code, 'code', 'INVALID_RANGE')),
      );
    });
  });
}
