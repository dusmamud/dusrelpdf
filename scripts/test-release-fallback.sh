#!/usr/bin/env bash
# Tests for scripts/release_fallback.sh and scripts/sync-versions.sh.
#
# Builds minimal scratch git repos in a temp dir (NOT the real repo):
# each fixture has a fake `dusrelpdf-v0.1.0` tag, a 0.1.0 workspace
# version, and the same version files the real repo has — then runs the
# REAL scripts (copied from this repo) against them.
#
# Usage: bash scripts/test-release-fallback.sh
# Exit 0 only if every case passes.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
PASS=0
FAIL=0

ok()   { PASS=$((PASS + 1)); echo "PASS: $1"; }
bad()  { FAIL=$((FAIL + 1)); echo "FAIL: $1"; }
check_eq() { # check_eq <label> <got> <want>
  if [ "$2" = "$3" ]; then ok "$1"; else bad "$1 (got '$2', want '$3')"; fi
}

# make_fixture <dir>: minimal repo at version 0.1.0, no tag yet.
make_fixture() {
  local dir="$1"
  mkdir -p "$dir"/{crates/dusrelpdf/src,crates/dusrelpdf-cli,crates/dusrelpdf-ffi,crates/dusrelpdf-napi,crates/dusrelpdf-py,crates/dusrelpdf-uniffi,crates/dusrelpdf-wasm,packages/js,packages/flutter/dusrelpdf,packages/go,bindings/kotlin,website,scripts}
  cp "$REPO_ROOT/scripts/release_fallback.sh" "$REPO_ROOT/scripts/sync-versions.sh" "$dir/scripts/"
  cd "$dir"
  git init -q -b main
  git config user.name "test"
  git config user.email "test@example.invalid"
  cat > Cargo.toml <<'EOF'
[workspace]
members = [
    "crates/dusrelpdf",
    "crates/dusrelpdf-cli",
    "crates/dusrelpdf-uniffi",
    "crates/dusrelpdf-py",
    "crates/dusrelpdf-wasm",
    "crates/dusrelpdf-napi",
    "crates/dusrelpdf-ffi",
]
resolver = "2"

[workspace.package]
version = "0.1.0"
edition = "2024"
EOF
  cat > Cargo.lock <<'EOF'
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "byteorder-lite"
version = "0.1.0"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "dusrelpdf"
version = "0.1.0"

[[package]]
name = "dusrelpdf-cli"
version = "0.1.0"

[[package]]
name = "dusrelpdf-ffi"
version = "0.1.0"

[[package]]
name = "dusrelpdf-napi"
version = "0.1.0"

[[package]]
name = "dusrelpdf-py"
version = "0.1.0"

[[package]]
name = "dusrelpdf-uniffi"
version = "0.1.0"

[[package]]
name = "dusrelpdf-wasm"
version = "0.1.0"

[[package]]
name = "simd_helpers"
version = "0.1.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
EOF
  cat > CHANGELOG.md <<'EOF'
# Changelog

All notable changes to dusrelpdf are documented here.

## [Unreleased]

### Added

- Phase 2 bindings, same 0.1.0 core, nothing published yet.

## [0.1.0] - 2026-11-12

### Added

- First release.
EOF
  echo 'pub fn merge() {}' > crates/dusrelpdf/src/lib.rs
  echo '{"name":"dusrelpdf","version":"0.1.0"}' > packages/js/package.json
  printf '{\n  "name": "dusrelpdf",\n  "version": "0.1.0",\n  "packages": {\n    "": {\n      "name": "dusrelpdf",\n      "version": "0.1.0"\n    },\n    "node_modules/dep": {\n      "version": "4.68.2"\n    }\n  }\n}\n' > packages/js/package-lock.json
  printf '{\n  "name": "dusrelpdf-napi",\n  "version": "0.1.0"\n}\n' > crates/dusrelpdf-napi/package.json
  printf '{\n  "name": "dusrelpdf-napi",\n  "version": "0.1.0",\n  "packages": {\n    "": {\n      "name": "dusrelpdf-napi",\n      "version": "0.1.0"\n    }\n  }\n}\n' > crates/dusrelpdf-napi/package-lock.json
  printf '[project]\nname = "dusrelpdf"\nversion = "0.1.0"\n' > crates/dusrelpdf-py/pyproject.toml
  printf 'name: dusrelpdf\ndescription: test\nversion: 0.1.0\n' > packages/flutter/dusrelpdf/pubspec.yaml
  printf '{"name":"dusrelpdf-website","version":"0.1.0"}' > website/package.json
  printf "export default { softwareVersion: '0.1.0' };\n" > website/astro.config.mjs
  printf 'package dusrelpdf\n\n// Version returns the library version, e.g. "0.1.0".\nfunc Version() string { return "0.1.0" }\n' > packages/go/dusrelpdf.go
  printf 'package dusrelpdf\n\nimport "testing"\n\nfunc TestVersion(t *testing.T) {\n\tif v := Version(); v != "0.1.0" {\n\t\tt.Fatalf("Version() = %q, want 0.1.0", v)\n\t}\n}\n' > packages/go/dusrelpdf_test.go
  echo 'satellite kotlin binding' > bindings/kotlin/binding.kt
  echo '# dusrelpdf' > README.md
  git add -A
  git commit -qm "0.1.0 baseline"
  cd "$REPO_ROOT"
}

all_version_files_read() { # all_version_files_read <dir> <want>
  local dir="$1" want="$2"
  grep -qE "\"version\": *\"$want\"" "$dir/packages/js/package.json" &&
  grep -q "\"version\": \"$want\"" "$dir/packages/js/package-lock.json" &&
  grep -q "\"version\": \"$want\"" "$dir/crates/dusrelpdf-napi/package.json" &&
  grep -q "\"version\": \"$want\"" "$dir/crates/dusrelpdf-napi/package-lock.json" &&
  grep -q "^version = \"$want\"" "$dir/crates/dusrelpdf-py/pyproject.toml" &&
  grep -q "^version: $want" "$dir/packages/flutter/dusrelpdf/pubspec.yaml" &&
  grep -qE "\"version\": *\"$want\"" "$dir/website/package.json" &&
  grep -q "softwareVersion: '$want'" "$dir/website/astro.config.mjs" &&
  grep -q "want $want" "$dir/packages/go/dusrelpdf_test.go" &&
  grep -q "e.g. \"$want\"" "$dir/packages/go/dusrelpdf.go"
}

# --- Case 1: satellite-only change -> bump to 0.1.1 -------------------
d="$TMP/case1"
make_fixture "$d"
cd "$d"
git tag dusrelpdf-v0.1.0
echo 'more flutter' >> packages/flutter/dusrelpdf/pubspec.yaml
git add -A && git commit -qm "feat: flutter tweaks"
if out=$(bash scripts/release_fallback.sh check 2>"$TMP/case1.err"); then rc=0; else rc=$?; fi
check_eq "case1 check exits 0" "$rc" "0"
check_eq "case1 check prints NEW_VERSION=0.1.1" "$out" "NEW_VERSION=0.1.1"
if out=$(bash scripts/release_fallback.sh apply 2>"$TMP/case1-apply.err"); then rc=0; else rc=$?; fi
check_eq "case1 apply exits 0" "$rc" "0"
check_eq "case1 apply prints NEW_VERSION=0.1.1" "$out" "NEW_VERSION=0.1.1"
check_eq "case1 Cargo.toml bumped" "$(grep -m1 '^version =' Cargo.toml)" 'version = "0.1.1"'
if all_version_files_read "$d" "0.1.1"; then ok "case1 all synced files read 0.1.1"; else bad "case1 all synced files read 0.1.1"; fi
# Lock: the 7 workspace members bumped, decoy third-party 0.1.0 crates untouched.
lock_members=$(grep -A1 'name = "dusrelpdf' Cargo.lock | grep -c 'version = "0.1.1"' || true)
check_eq "case1 Cargo.lock: 7 workspace members at 0.1.1" "$lock_members" "7"
if grep -A1 'name = "byteorder-lite"' Cargo.lock | grep -q 'version = "0.1.0"' &&
   grep -A1 'name = "simd_helpers"' Cargo.lock | grep -q 'version = "0.1.0"'; then
  ok "case1 Cargo.lock: decoy deps still 0.1.0"
else
  bad "case1 Cargo.lock: decoy deps still 0.1.0"
fi
# Lock: dependency version inside js lock untouched by sync.
if grep -q '"version": "4.68.2"' packages/js/package-lock.json; then ok "case1 js lock dep version untouched"; else bad "case1 js lock dep version untouched"; fi
if grep -q "^## \[0.1.1\] - " CHANGELOG.md && grep -q "Phase 2 bindings" CHANGELOG.md; then
  ok "case1 changelog has dated [0.1.1] with moved Unreleased notes"
else
  bad "case1 changelog has dated [0.1.1] with moved Unreleased notes"
fi
if awk '/## \[Unreleased\]/{f=1;next} /## \[/{f=0} f' CHANGELOG.md | grep -q '[^[:space:]]'; then
  bad "case1 Unreleased left empty"
else
  ok "case1 Unreleased left empty"
fi
# Applying again must NOT double-bump (local 0.1.1 != tag 0.1.0).
if bash scripts/release_fallback.sh check >/dev/null 2>&1; then bad "case1 second check still bumps (must not)"; else ok "case1 second check refuses (no double bump)"; fi
cd "$REPO_ROOT"

# --- Case 2: no change since tag -> no bump ---------------------------
d="$TMP/case2"
make_fixture "$d"
cd "$d"
git tag dusrelpdf-v0.1.0
if bash scripts/release_fallback.sh check >/dev/null 2>"$TMP/case2.err"; then
  bad "case2 no-change check must exit 1"
else
  ok "case2 no-change check exits 1"
  grep -q "no satellite changes" "$TMP/case2.err" && ok "case2 reason mentions no satellite changes" || bad "case2 reason mentions no satellite changes"
fi
cd "$REPO_ROOT"

# --- Case 3: core-only change -> leave to release-plz ------------------
d="$TMP/case3"
make_fixture "$d"
cd "$d"
git tag dusrelpdf-v0.1.0
echo '// core fix' >> crates/dusrelpdf/src/lib.rs
git add -A && git commit -qm "fix: core"
if bash scripts/release_fallback.sh check >/dev/null 2>"$TMP/case3.err"; then
  bad "case3 core-only check must exit 1"
else
  ok "case3 core-only check exits 1"
  grep -q "release-plz handles" "$TMP/case3.err" && ok "case3 reason defers to release-plz" || bad "case3 reason defers to release-plz"
fi
cd "$REPO_ROOT"

# --- Case 4: no tag at all -> FIRST release, no bump ------------------
# release-plz cannot see a first release (no conventional core commit),
# so the fallback opens it: version stays 0.1.0, only the changelog
# moves. Re-checking after apply still says yes — that is by design:
# until the release PR merges and the tag exists, a re-dispatch must
# be able to re-open the PR (the workflow's open-PR guard is what
# stops duplicates while it is open).
d="$TMP/case4"
make_fixture "$d"
cd "$d"
echo 'more' >> bindings/kotlin/binding.kt
git add -A && git commit -qm "feat: binding"
if out=$(bash scripts/release_fallback.sh check 2>"$TMP/case4.err"); then rc=0; else rc=$?; fi
check_eq "case4 no-tag check exits 0 (first release)" "$rc" "0"
check_eq "case4 check prints NEW_VERSION=0.1.0 + first_release=true" "$out" "NEW_VERSION=0.1.0
first_release=true"
if out=$(bash scripts/release_fallback.sh apply 2>"$TMP/case4-apply.err"); then rc=0; else rc=$?; fi
check_eq "case4 apply exits 0" "$rc" "0"
check_eq "case4 apply prints NEW_VERSION=0.1.0 + first_release=true" "$out" "NEW_VERSION=0.1.0
first_release=true"
check_eq "case4 Cargo.toml NOT bumped (still 0.1.0)" "$(grep -m1 '^version =' Cargo.toml)" 'version = "0.1.0"'
if [ "$(git status --porcelain | awk '{print $2}')" = "CHANGELOG.md" ]; then
  ok "case4 only CHANGELOG.md changed"
else
  bad "case4 only CHANGELOG.md changed: $(git status --porcelain)"
fi
if grep -q "^## \[0.1.0\] - " CHANGELOG.md && grep -q "Phase 2 bindings" CHANGELOG.md; then
  ok "case4 changelog has dated [0.1.0] with moved Unreleased notes"
else
  bad "case4 changelog has dated [0.1.0] with moved Unreleased notes"
fi
cd "$REPO_ROOT"

# --- Case 5: local version already ahead of tag -> no bump -------------
d="$TMP/case5"
make_fixture "$d"
cd "$d"
git tag dusrelpdf-v0.1.0
sed -i 's/version = "0.1.0"/version = "0.1.1"/' Cargo.toml
git add -A && git commit -qm "chore: release v0.1.1"
if bash scripts/release_fallback.sh check >/dev/null 2>"$TMP/case5.err"; then
  bad "case5 version-ahead check must exit 1"
else
  ok "case5 version-ahead check exits 1"
fi
cd "$REPO_ROOT"

# --- Case 6: mixed core + satellite -> leave to release-plz -------------
d="$TMP/case6"
make_fixture "$d"
cd "$d"
git tag dusrelpdf-v0.1.0
echo '// core fix' >> crates/dusrelpdf/src/lib.rs
echo 'more' >> bindings/kotlin/binding.kt
git add -A && git commit -qm "fix: core + binding"
if bash scripts/release_fallback.sh check >/dev/null 2>&1; then
  bad "case6 mixed check must exit 1"
else
  ok "case6 mixed check exits 1 (core present, release-plz owns it)"
fi
cd "$REPO_ROOT"

# --- Case 7: sync-versions.sh is idempotent + actually syncs -----------
d="$TMP/case7"
make_fixture "$d"
cd "$d"
# Round-trip to the same version: no file may change.
bash scripts/sync-versions.sh 0.1.0 > /dev/null
if [ -z "$(git status --porcelain)" ]; then ok "case7 sync round-trip to 0.1.0 changes nothing"; else bad "case7 sync round-trip to 0.1.0 changes nothing: $(git status --porcelain)"; fi
# No-arg form reads Cargo.toml (0.1.0): also a no-op.
bash scripts/sync-versions.sh > /dev/null
if [ -z "$(git status --porcelain)" ]; then ok "case7 sync no-arg round-trip changes nothing"; else bad "case7 sync no-arg round-trip changes nothing"; fi
# Setting a different version changes every synced file.
bash scripts/sync-versions.sh 0.1.1 > /dev/null
if all_version_files_read "$d" "0.1.1"; then ok "case7 sync to 0.1.1 updates every file"; else bad "case7 sync to 0.1.1 updates every file"; fi
if grep -q '"version": "4.68.2"' packages/js/package-lock.json; then ok "case7 sync leaves lock dep versions alone"; else bad "case7 sync leaves lock dep versions alone"; fi
# Running the same sync again must change nothing further.
before=$(git status --porcelain)
bash scripts/sync-versions.sh 0.1.1 > /dev/null
after=$(git status --porcelain)
if [ "$before" = "$after" ]; then ok "case7 sync to 0.1.1 twice is a no-op the second time"; else bad "case7 sync to 0.1.1 twice is a no-op the second time"; fi
cd "$REPO_ROOT"

# --- Case 8: bare v* tag + empty [Unreleased] -> generated entry -----
d="$TMP/case8"
make_fixture "$d"
cd "$d"
# Empty the [Unreleased] section (no hand-written notes to move).
python3 - <<'PYEOF2'
text = open("CHANGELOG.md").read()
start = text.index("## [Unreleased]")
end = text.index("## [0.1.0]")
open("CHANGELOG.md", "w").write(text[:start] + "## [Unreleased]\n\n" + text[end:])
PYEOF2
git add -A && git commit -qm "docs: empty unreleased"
git tag v0.1.0
echo 'more' >> bindings/kotlin/binding.kt
echo 'more go' >> packages/go/dusrelpdf.go
git add -A && git commit -qm "feat: bindings + go"
if out=$(bash scripts/release_fallback.sh apply 2>"$TMP/case8.err"); then rc=0; else rc=$?; fi
check_eq "case8 apply with bare v tag exits 0" "$rc" "0"
check_eq "case8 apply prints NEW_VERSION=0.1.1" "$out" "NEW_VERSION=0.1.1"
if grep -q "^## \[0.1.1\] - " CHANGELOG.md &&
   grep -q "Satellite-only release: no changes to the Rust core" CHANGELOG.md &&
   grep -q "^- bindings/kotlin" CHANGELOG.md &&
   grep -q "^- packages/go" CHANGELOG.md; then
  ok "case8 changelog has generated [0.1.1] entry with areas"
else
  bad "case8 changelog has generated [0.1.1] entry with areas"
fi
cd "$REPO_ROOT"

echo
echo "test-release-fallback: $PASS passed, $FAIL failed"
[ "$FAIL" -eq 0 ]
